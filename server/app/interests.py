def normalize(word: str) -> str | None:
    word = word.strip()
    if word in INTEREST_TERMS:
        return word
    return INTEREST_ALIASES.get(word)


def terms(interest: str) -> tuple[str, ...]:
    return INTEREST_TERMS.get(interest, (interest,))


def search_query(interest: str) -> str:
    """장소 검색어. 관련어의 첫 단어 ('물고기' → '아쿠아리움')."""
    return terms(interest)[0]


def vocabulary() -> list[str]:
    """파서가 찾을 단어. 긴 단어부터 맞춰 '그림책'이 '그림'보다 먼저 잡히게 한다."""
    return sorted({*INTEREST_TERMS, *INTEREST_ALIASES}, key=len, reverse=True)
