    val Dock = 28.dp
    val Large = 40.dp
}

/** 선 아이콘을 [tint] 색으로 그린다. [size]가 null이면 아이콘 원본 크기. */
@Composable
fun SitterIcon(icon: ImageVector, tint: Color, modifier: Modifier = Modifier, size: Dp? = null) {
    Image(
        imageVector = icon,
        contentDescription = null,
        colorFilter = ColorFilter.tint(tint),
        modifier = if (size != null) modifier.size(size) else modifier.size(icon.defaultWidth, icon.defaultHeight),
    )
}

