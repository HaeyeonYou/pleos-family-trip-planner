/**
 * 11/10 확정 디자인(Figma 351:2611)의 `icon/…` 선 아이콘 29종. `docs/design/pleos-1110/assets/icons/`의 Figma 원본 SVG에서
 * 경로·원본 크기·선 두께를 그대로 옮겼다 (옛 [FigmaIcons]와 모양·크기가 다를 수 있어 따로 둔다).
 * 색은 SVG에 박지 않고 쓰는 곳의 `tint`로 정한다. 새 아이콘은 SVG에서 같은 형식으로 추가한다.
 *
 * 규격: 원본 크기는 아이콘마다 다르다 (바로가기 28, 태그·행 22~26, 마이크 24). 화면에서는 [SitterIcon]에 `size`를
 * 따로 주지 말고 원본 크기를 쓰고, 꼭 바꿔야 할 때만 [SitterIconSize]의 값 중에서 고른다.
 */
private fun sitterIcon(name: String, size: Int, strokeWidth: Float, vararg paths: String): ImageVector =
    ImageVector.Builder(name = name, defaultWidth = size.dp, defaultHeight = size.dp, viewportWidth = size.toFloat(), viewportHeight = size.toFloat())
        .apply {
            paths.forEach { d ->
                addPath(
                    pathData = addPathNodes(d),
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = strokeWidth,
                    strokeLineCap = StrokeCap.Round,
                    strokeLineJoin = StrokeJoin.Round,
                )
            }
        }.build()

/** 아이콘 크기 단계. Figma 원본이 쓰는 크기 중 화면 용도별로 고른다. */
